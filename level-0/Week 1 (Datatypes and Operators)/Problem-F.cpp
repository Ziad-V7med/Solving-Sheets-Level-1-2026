#include <iostream>
using namespace std; 

int main(){
    int n,m; 
    cin>>n>>m; 
    cout<<n<<" + "<<m<<" = "<<(long long)n+(long long)m<<endl;
    cout<<n<<" - "<<m<<" = "<<n-m<<endl;
    cout<<n<<" * "<<m<<" = "<<(long long)n*(long long)m<<endl;
    cout<<n<<" / "<<m<<" = "<<n/m<<endl;
    cout<<n<<" % "<<m<<" = "<<n%m<<endl;

    return 0; 
    
}
